// Package state persists the execution status of a scenario so that a run
// can be resumed after an interruption (orchestrator `resume` mode).
package state

import (
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"sync"
	"time"
)

// Status is the lifecycle status of a step.
type Status string

const (
	StatusPending Status = "pending"
	StatusRunning Status = "running"
	StatusDone    Status = "done"
	StatusFailed  Status = "failed"
	StatusSkipped Status = "skipped"
)

// StepRecord is the persisted information about one step.
type StepRecord struct {
	Status     Status `json:"status"`
	StartedAt  string `json:"started_at,omitempty"`
	FinishedAt string `json:"finished_at,omitempty"`
	Error      string `json:"error,omitempty"`
}

// State is the persisted execution state of a scenario.
type State struct {
	Scenario string                `json:"scenario"`
	Steps    map[string]StepRecord `json:"steps"`
	Env      map[string]string     `json:"env,omitempty"`

	mu sync.RWMutex // guards concurrent updates (crash-safe writers).
}

// New returns an empty state for the given scenario with every step pending.
func New(scenario string) *State {
	return &State{Scenario: scenario, Steps: map[string]StepRecord{}, Env: map[string]string{}}
}

// Load reads the state file at path. A missing file is not an error: an
// empty state is returned for the scenario.
func Load(scenario, path string) (*State, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return New(scenario), nil
		}
		return nil, fmt.Errorf("load state %q: %w", path, err)
	}
	var st State
	if err := json.Unmarshal(data, &st); err != nil {
		return nil, fmt.Errorf("parse state %q: %w", path, err)
	}
	if st.Steps == nil {
		st.Steps = map[string]StepRecord{}
	}
	if st.Env == nil {
		st.Env = map[string]string{}
	}
	if st.Scenario == "" {
		st.Scenario = scenario
	}
	return &st, nil
}

// Save writes the state atomically (write-then-rename) to path.
func (s *State) Save(path string) error {
	s.mu.RLock()
	data, err := json.MarshalIndent(s, "", "  ")
	s.mu.RUnlock()
	if err != nil {
		return fmt.Errorf("encode state: %w", err)
	}

	if dir := filepath.Dir(path); dir != "." {
		if err := os.MkdirAll(dir, 0o700); err != nil {
			return fmt.Errorf("create state dir %q: %w", dir, err)
		}
		if err := os.Chmod(dir, 0o700); err != nil {
			return fmt.Errorf("protect state dir %q: %w", dir, err)
		}
	}

	tmp := path + ".tmp"
	defer func() { _ = os.Remove(tmp) }()
	f, err := os.OpenFile(tmp, os.O_CREATE|os.O_TRUNC|os.O_WRONLY, 0o600)
	if err != nil {
		return fmt.Errorf("write state %q: %w", tmp, err)
	}
	if err := f.Chmod(0o600); err != nil {
		_ = f.Close()
		return fmt.Errorf("protect state %q: %w", tmp, err)
	}
	if _, err := f.Write(data); err != nil {
		_ = f.Close()
		return fmt.Errorf("write state %q: %w", tmp, err)
	}
	if err := f.Sync(); err != nil {
		_ = f.Close()
		return fmt.Errorf("sync state %q: %w", tmp, err)
	}
	if err := f.Close(); err != nil {
		return fmt.Errorf("close state %q: %w", tmp, err)
	}
	if err := os.Rename(tmp, path); err != nil {
		return fmt.Errorf("finalize state %q: %w", path, err)
	}
	return nil
}

// Environment returns a copy of the scenario's persisted runtime environment.
func (s *State) Environment() map[string]string {
	s.mu.RLock()
	defer s.mu.RUnlock()
	copy := make(map[string]string, len(s.Env))
	for key, value := range s.Env {
		copy[key] = value
	}
	return copy
}

// SetEnvironment stores a value produced by the scenario or generated by the
// orchestrator. These values may include credentials, so State.Save writes
// them with owner-only permissions.
func (s *State) SetEnvironment(key, value string) {
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.Env == nil {
		s.Env = map[string]string{}
	}
	s.Env[key] = value
}

// SetRecord replaces the record of a step.
func (s *State) SetRecord(stepID string, rec StepRecord) {
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.Steps == nil {
		s.Steps = map[string]StepRecord{}
	}
	s.Steps[stepID] = rec
}

// Begin marks a step as running.
func (s *State) Begin(stepID string) {
	s.SetRecord(stepID, StepRecord{Status: StatusRunning, StartedAt: time.Now().Format(time.RFC3339)})
}

// Finish marks a step as done or failed and stores an optional error message.
// The started_at timestamp of the running record is preserved.
func (s *State) Finish(stepID string, status Status, errMsg string) {
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.Steps == nil {
		s.Steps = map[string]StepRecord{}
	}
	prev, exists := s.Steps[stepID]
	startedAt := ""
	if exists {
		startedAt = prev.StartedAt
	}
	s.Steps[stepID] = StepRecord{
		Status:     status,
		StartedAt:  startedAt,
		FinishedAt: time.Now().Format(time.RFC3339),
		Error:      errMsg,
	}
}

// Skip marks a step as skipped.
func (s *State) Skip(stepID string) {
	s.SetRecord(stepID, StepRecord{Status: StatusSkipped, FinishedAt: time.Now().Format(time.RFC3339)})
}

// Status returns the persisted status of a step (pending when unknown).
func (s *State) Status(stepID string) Status {
	s.mu.RLock()
	defer s.mu.RUnlock()
	rec, ok := s.Steps[stepID]
	if !ok {
		return StatusPending
	}
	return rec.Status
}
